// Static build: content/*.json + components -> dist/
//
//   node src/build.mjs
//
// Environment (all optional):
//   SITE_URL                  absolute origin used for canonical/hreflang/sitemap
//                             (default: site.json "url")
//   BASE_PATH                 serve from a sub-path, e.g. "/parish" (default "")
//   ORTHODOXCONNECT_FEED_URL  fetch a live OrthodoxConnect feed at build time
//                             instead of the bundled sample
//   OUT_DIR                   output folder (default "dist")
//   CONTENT_DIR, PUBLIC_DIR   build another parish's content folder and
//                             static files (defaults "content", "public")
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { loadContent, readJson, themeFile, ROOT, PUBLIC_DIR } from './lib/content.mjs';
import { createContext } from './lib/context.mjs';
import { renderPage } from './components/layout.mjs';
import { tokensToCss, fontsToCss, preloadFonts } from './lib/tokens.mjs';

const OUT = path.resolve(ROOT, process.env.OUT_DIR || 'dist');
const BASE_PATH = (process.env.BASE_PATH || '').replace(/\/$/, '');
const STYLE_ORDER = ['base.css', 'layout.css', 'components.css', 'forms.css', 'sections.css', 'modules.css', 'utilities.css'];

async function loadFeed() {
  const url = process.env.ORTHODOXCONNECT_FEED_URL;
  if (!url) return undefined;
  try {
    const res = await fetch(url, { headers: { accept: 'application/json' } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const feed = await res.json();
    const { validateFeed } = await import('../scripts/validate.mjs');
    const errors = validateFeed(feed);
    if (errors.length) throw new Error(`feed does not match schema:\n  ${errors.join('\n  ')}`);
    console.log(`OrthodoxConnect: using live feed (${feed.items.length} items)`);
    return feed;
  } catch (err) {
    console.warn(`OrthodoxConnect: could not use ${url} (${err.message}); falling back to the sample feed.`);
    return undefined;
  }
}

function hash(text) {
  return crypto.createHash('sha256').update(text).digest('hex').slice(0, 10);
}

function writeFile(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
}

// site.js = the shared calendar module (exports stripped, so the browser
// computes feasts and dates exactly like the build) + src/client/*.js in
// CLIENT_ORDER, in one closure (src/client/core.js explains the handler hooks).
const CLIENT_ORDER = ['core.js', 'header.js', 'schedule.js', 'schedule-detail.js', 'live.js', 'filters.js', 'media.js', 'forms.js', 'cart.js', 'zapiski.js', 'connect.js'];

function clientScript() {
  const calendar = fs
    .readFileSync(path.join(ROOT, 'src/lib/calendar.mjs'), 'utf8')
    .replace(/^export\s+/gm, '')
    .replace(/^import .*$/gm, '');
  const files = fs.readdirSync(path.join(ROOT, 'src/client')).filter((f) => f.endsWith('.js'));
  const missing = files.filter((f) => !CLIENT_ORDER.includes(f));
  if (missing.length) throw new Error(`src/client: add ${missing.join(', ')} to CLIENT_ORDER in src/build.mjs`);
  // core.js shares its helpers with the others; every other file gets its own scope.
  const parts = CLIENT_ORDER.filter((f) => files.includes(f)).map((f) => {
    const code = fs.readFileSync(path.join(ROOT, 'src/client', f), 'utf8');
    return f === 'core.js' ? `// ---- ${f}\n${code}` : `// ---- ${f}\n(function () {\n${code}\n})();`;
  });
  return `/* Generated by src/build.mjs from src/lib/calendar.mjs and src/client/. */\n(function () {\n'use strict';\n${calendar}\n${parts.join('\n')}\n})();\n`;
}

function buildAssets(site) {
  const file = themeFile();
  const tokens = readJson(file);
  const styles = STYLE_ORDER.map((name) => fs.readFileSync(path.join(ROOT, 'src/styles', name), 'utf8'));
  const css = [`/* Generated from ${path.relative(ROOT, file)} */\n${fontsToCss(tokens)}\n\n${tokensToCss(tokens)}`, ...styles]
    .join('\n\n')
    .replace(/url\((["']?)\/(?!\/)/g, `url($1${BASE_PATH}/`);
  const js = clientScript();
  writeFile(path.join(OUT, 'assets/site.css'), css);
  writeFile(path.join(OUT, 'assets/site.js'), js);
  writeFile(path.join(OUT, 'assets/tokens.css'), tokensToCss(tokens));
  return {
    cssHref: `${BASE_PATH}/assets/site.css?v=${hash(css)}`,
    jsHref: `${BASE_PATH}/assets/site.js?v=${hash(js)}`,
    preloadFonts: preloadFonts(tokens),
    themeColor: tokens.color?.navy || '#174372'
  };
}

function pageFile(locale, page) {
  return path.join(OUT, locale, page.path || '', 'index.html');
}

// Forwards to `suffix` (path after the locale, e.g. "choir/#concerts") in the
// visitor's language: stored choice, then browser language, then sourceLocale.
function redirectPage(content, siteUrl, suffix = '') {
  const { site } = content;
  const codes = site.locales.map((l) => l.code);
  const [pathPart, hash = ''] = suffix.split('#');
  const target = `${BASE_PATH}/${site.sourceLocale}/${pathPart}`;
  const at = (code) => `${BASE_PATH}/${code}/${pathPart}${hash ? `#${hash}` : ''}`;
  return `<!doctype html>
<html lang="${site.sourceLocale}">
<head>
<meta charset="utf-8">
<title>${site.seo.siteName[site.sourceLocale]}</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<link rel="canonical" href="${siteUrl}${target}">
${pathPart ? '' : `${site.locales.map((l) => `<link rel="alternate" hreflang="${l.code}" href="${siteUrl}${BASE_PATH}/${l.code}/">`).join('\n')}\n<link rel="alternate" hreflang="x-default" href="${siteUrl}${target}">\n`}<script>
(function () {
  var codes = ${JSON.stringify(codes)}, pick = null;
  try { pick = localStorage.getItem('site-lang'); } catch (e) {}
  if (codes.indexOf(pick) < 0) {
    pick = null;
    var langs = navigator.languages || [navigator.language || ''];
    for (var i = 0; i < langs.length && !pick; i++) {
      var c = String(langs[i]).slice(0, 2).toLowerCase();
      if (codes.indexOf(c) >= 0) pick = c;
    }
  }
  location.replace(${JSON.stringify(BASE_PATH)} + '/' + (pick || ${JSON.stringify(site.sourceLocale)}) + '/' + ${JSON.stringify(pathPart)} + (location.hash || ${JSON.stringify(hash ? `#${hash}` : '')}));
})();
</script>
<noscript><meta http-equiv="refresh" content="0; url=${at(site.sourceLocale)}"></noscript>
</head>
<body>
<p>${site.locales.map((l) => `<a href="${at(l.code)}" hreflang="${l.code}">${l.name}</a>`).join(' · ')}</p>
</body>
</html>
`;
}

function sitemap(content, siteUrl) {
  const { site, pages } = content;
  const codes = site.locales.map((l) => l.code);
  const loc = (code, page) => `${siteUrl}${BASE_PATH}/${code}/${page.path ? `${page.path}/` : ''}`;
  const urls = pages
    .filter((p) => p.sitemap !== false && p.id !== 'not-found')
    .flatMap((page) =>
      codes.map(
        (code) => `  <url>
    <loc>${loc(code, page)}</loc>
${codes.map((c) => `    <xhtml:link rel="alternate" hreflang="${c}" href="${loc(c, page)}"/>`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${loc(site.sourceLocale, page)}"/>
  </url>`
      )
    );
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join('\n')}
</urlset>
`;
}

export async function build() {
  const started = Date.now();
  const feed = await loadFeed();
  const content = loadContent({ feedOverride: feed });
  const siteUrl = (process.env.SITE_URL || content.site.url).replace(/\/$/, '');

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.cpSync(PUBLIC_DIR, OUT, { recursive: true });
  const assets = buildAssets(content.site);

  let count = 0;
  for (const page of content.pages) {
    for (const { code } of content.site.locales) {
      const ctx = createContext({ content, locale: code, page, basePath: BASE_PATH, siteUrl });
      try {
        writeFile(pageFile(code, page), renderPage(ctx, assets));
      } catch (err) {
        err.message = `[${code}/${page.id}] ${err.message}`;
        throw err;
      }
      count++;
    }
  }

  const notFound = content.index.pages['not-found'];
  if (notFound) fs.copyFileSync(pageFile(content.site.sourceLocale, notFound), path.join(OUT, '404.html'));
  writeFile(path.join(OUT, 'index.html'), redirectPage(content, siteUrl));
  for (const r of content.redirects) {
    const page = content.index.pages[r.page];
    if (!page) continue;
    const file = path.join(OUT, r.from);
    if (fs.existsSync(file)) throw new Error(`redirect "${r.from}" would overwrite a built file`);
    writeFile(file, redirectPage(content, siteUrl, `${page.path ? `${page.path}/` : ''}${r.anchor ? `#${r.anchor}` : ''}`));
  }
  writeFile(path.join(OUT, 'sitemap.xml'), sitemap(content, siteUrl));
  writeFile(path.join(OUT, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}${BASE_PATH}/sitemap.xml\n`);
  console.log(`Built ${count} pages (${content.site.locales.map((l) => l.code).join(', ')}) into ${path.relative(ROOT, OUT)}/ in ${Date.now() - started} ms`);
  return { content, out: OUT };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  build().catch((err) => {
    console.error(err.stack || err.message);
    process.exit(1);
  });
}
